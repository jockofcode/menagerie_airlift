# Open water for a level: each pool's surface, spread out to where it meets
# the banks.
def build_water(pts, pools)
  table = build_terrain_table(pts)
  out = []
  pools.each do |p|
    s = p[2] - WATER_DEPTH
    x0 = p[0]
    x0 -= TERRAIN_STEP while table_y(table, x0 - TERRAIN_STEP) > s && x0 > WORLD_L
    x1 = p[1]
    x1 += TERRAIN_STEP while table_y(table, x1 + TERRAIN_STEP) > s && x1 < WORLD_R
    out.push([x0, x1, s])
  end
  out
end

def table_y(table, x)
  f = (x - WORLD_L) / TERRAIN_STEP
  f = 0.0 if f < 0.0
  last = table.length - 2
  f = last.to_f if f > last
  i = f.to_i
  k = f - i
  table[i] + (table[i + 1] - table[i]) * k
end

