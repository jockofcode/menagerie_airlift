# The levels. Every level shares the layout the demo AI is tuned to (the
# four ledges, the base, the border sign) and the rules; each has its own
# terrain between the ledges, its own art set (lib/capri/levels/*_art.rb),
# its own voices (lib/capri/levels/*_sound.rb), the words on its screens,
# the colors its effects throw up, and at most one twist of its own:
#
# - fjords:     trolls are stone by day (they don't move or throw) and
#               fiercer at night.
# - bayou and highlands: open water between the clearings; setting down
#               in it sinks the chopper.
# - outback:    drop bears wait in the gum trees on the ledges and let go
#               onto a chopper that comes in low beneath them.
# - desert:     dust devils wander the slopes and shove the chopper about.
# - moon:       the chopper is a spaceship: lasers that fly straight (no
#               drop with range), photon torpedoes for charges, engine
#               flames for rotors, and a black, starry sky with the Earth.
# - volcano:    after a tremor, the vents in the slopes throw lava bombs.
# - jungle:     vines grow over the ruins; the first charge only cuts them.
# - himalaya:   thin air: the chopper climbs more weakly the higher it is.
# - undersea:   a submarine (torpedoes, depth charges, a propeller wash
#               for rotors) in open water with no sun; currents (dust
#               devils by another name) push it about.
# - savanna:    now and then a herd stampedes along the ground toward the
#               fence; anything on or near the ground in its path is hit.
# - mars:       a spaceship like the moon's; dust storms blow up and hide
#               everything but the ship itself.
# - valentine:  Cupid's arrows stun the chopper (no control for a moment)
#               instead of wrecking it.
# - july4:      a night flight; fireworks go up off the slopes, and a
#               rocket that hits the chopper wrecks it.
#
# Seven are seasonal: Lunar New Year (a week before to two weeks after
# the new moon), Valentine's (February 7-14), St Patrick's (March
# 10-17), Easter (the week before Easter Sunday and the Monday), the
# Fourth of July (June 28 to July 5), Halloween (October 17 through
# November 1) and the North Pole (December). Out of season they can
# still be picked on the title screen, but missions only rotate through
# them in season; in season the title screen starts on them.
# CAPRI_SEASON=1 treats them all as in season, =0 none.

