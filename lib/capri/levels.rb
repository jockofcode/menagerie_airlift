# Day of the year, 1 = January 1.
def day_of_year(y, m, d)
  days = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334]
  n = days[m - 1] + d
  leap = (y % 4 == 0 && y % 100 != 0) || y % 400 == 0
  n += 1 if leap && m > 2
  n
end

# Easter Sunday's day of the year (the anonymous Gregorian algorithm).
def easter_day(y)
  a = y % 19
  b = y / 100
  c = y % 100
  d = b / 4
  e = b % 4
  f = (b + 8) / 25
  g = (b - f + 1) / 3
  h = (19 * a + b - d - g + 15) % 30
  i = c / 4
  k = c % 4
  l = (32 + 2 * e + 2 * i - h - k) % 7
  m = (a + 11 * h + 22 * l) / 451
  month = (h + l - 7 * m + 114) / 31
  day = ((h + l - 7 * m + 114) % 31) + 1
  day_of_year(y, month, day)
end

# Lunar New Year's day of the year, from a table (late January or
# February); outside it, February 1 as a stand-in.
LUNAR_NEW_YEARS = [
  [2025, 1, 29], [2026, 2, 17], [2027, 2, 6], [2028, 1, 26], [2029, 2, 13], [2030, 2, 3],
  [2031, 1, 23], [2032, 2, 11], [2033, 1, 31], [2034, 2, 19], [2035, 2, 8], [2036, 1, 28],
  [2037, 2, 15], [2038, 2, 4], [2039, 1, 24], [2040, 2, 12],
]

def lunar_new_year_day(y)
  LUNAR_NEW_YEARS.each { |e| return day_of_year(y, e[1], e[2]) if e[0] == y }
  day_of_year(y, 2, 1)
end

def in_season?(season, y, m, d)
  n = day_of_year(y, m, d)
  if season == SEASON_HALLOWEEN
    (m == 10 && d >= 17) || (m == 11 && d <= 1)
  elsif season == SEASON_DECEMBER
    m == 12
  elsif season == SEASON_LUNAR
    c = lunar_new_year_day(y)
    n >= c - 7 && n <= c + 15
  elsif season == SEASON_VALENTINE
    m == 2 && d >= 7 && d <= 14
  elsif season == SEASON_PATRICK
    m == 3 && d >= 10 && d <= 17
  elsif season == SEASON_EASTER
    c = easter_day(y)
    n >= c - 7 && n <= c + 1
  elsif season == SEASON_JULY4
    (m == 6 && d >= 28) || (m == 7 && d <= 5)
  else
    true
  end
end

# When a season comes round, for the title screen.
def season_when(season)
  return "OCT 17 - NOV 1" if season == SEASON_HALLOWEEN
  return "DECEMBER" if season == SEASON_DECEMBER
  return "LATE JAN - FEB" if season == SEASON_LUNAR
  return "FEB 7 - 14" if season == SEASON_VALENTINE
  return "MAR 10 - 17" if season == SEASON_PATRICK
  return "EASTER WEEK" if season == SEASON_EASTER
  return "JUN 28 - JUL 5" if season == SEASON_JULY4
  ""
end

def season_now(season)
  force = ENV["CAPRI_SEASON"]
  return force == "1" if force != nil && force.length > 0
  t = Time.now
  in_season?(season, t.year, t.month, t.day)
end

# Which levels are in season (the year-round ones always are).
IN_SEASON = LEVELS.map { |lv| lv.season == SEASON_NONE || season_now(lv.season) }

# How many missions one lap of the rotation takes.
def count_in_season
  n = 0
  IN_SEASON.each { |k| n += 1 if k }
  n
end
LEVELS_IN_SEASON = count_in_season

# The level the title screen starts on: a seasonal level in season, else
# the mountain.
def default_level
  i = 0
  while i < LEVEL_COUNT
    return i if LEVELS[i].season != SEASON_NONE && IN_SEASON[i]
    i += 1
  end
  0
end

def lv_info
  LEVELS[LEVEL[0]]
end
