class LevelInfo
  # Words: the picker name, the results-screen teaser, the creatures
  # (plural, for the HUD), the intro's "64 ..." line and its hint, the
  # title's how-to line, the perfect-mission cheer, the logo's subtitle,
  # and the bonus round's banner, its line and the two tally headings.
  attr_accessor :key, :name, :teaser, :animals, :intro, :hint, :how, :perfect, :logo,
                :bonus_title, :bonus_line, :bonus_all, :bonus_over,
                # What the bonus round drops (for its counter), and what you fly.
                :bonus_item, :craft,
                # Colors: feathers of the diving bird, the smoke and the bits a
                # blast throws up, the bits of a burst container, of a villain
                # driven off and of a smashed crate (plus a second spill, or
                # empty), the rotor wash on the mountain side and in the valley.
                :feather, :burst, :burst_bits, :drift_bits, :villain_bits, :crate_bits, :crate_spill,
                :wash_hill, :wash_valley,
                # Terrain points, open water ([x0, x1, surface y]), its colors.
                :pts, :water, :water_top, :water_deep,
                # Twists, the season, and northern lights at night.
                :trolls, :drop_bears, :dust_devils, :season, :aurora,
                # The craft: a spaceship (engine flames, no rotors), clouds in the
                # sky or a starry black one with the Earth, the cannon's rounds
                # (speed, starting drop and gravity a step, sprite size) and the
                # charges' sprite size.
                :ship, :clouds, :space, :shot_speed, :shot_drop, :shot_gravity, :shot_w, :shot_h,
                :bomb_w, :bomb_h,
                # More twists (see the list at the top), whether the villain's
                # missile turns to face where it flies (arrows, firecrackers),
                # whether the sky has a sun, moon and stars (not under the
                # sea), and how far into the day a mission starts (0 morning,
                # past 0.5 into the night).
                :volcano, :vines, :thin_air, :stampede, :dust_storm, :fireworks, :stun,
                :missile_aim, :celestial, :start_day

  def initialize(key, name)
    @key = key
    @name = name
    @teaser = name
    @animals = "GOATS"
    @intro = ""
    @hint = ""
    @how = ""
    @perfect = ""
    @logo = ""
    @bonus_title = "SUPPLY DROP"
    @bonus_line = ""
    @bonus_all = ""
    @bonus_over = ""
    @bonus_item = "CRATES"
    @craft = "CHOPPER"
    @feather = [0.45, 0.32, 0.18]
    @burst = [0.95, 0.97, 1.0]
    @burst_bits = [0.95, 0.97, 1.0]
    @drift_bits = [0.92, 0.95, 1.0]
    @villain_bits = [0.92, 0.94, 1.0]
    @crate_bits = [0.62, 0.44, 0.24]
    @crate_spill = [0.0, 0.0, 0.0]
    @wash_hill = [0.94, 0.96, 1.0]
    @wash_valley = [0.75, 0.65, 0.45]
    @pts = [[WORLD_L, 584.0], [WORLD_R + 100.0, 584.0]]
    @ship = false
    @clouds = true
    @space = false
    @shot_speed = BULLET_SPEED
    @shot_drop = BULLET_DROP
    @shot_gravity = BULLET_GRAVITY
    @shot_w = 16.0
    @shot_h = 6.0
    @bomb_w = 12.0
    @bomb_h = 18.0
    @water = [[0.0, 0.0, 0.0]]
    @water_top = [0.0, 0.0, 0.0]
    @water_deep = [0.0, 0.0, 0.0]
    @trolls = false
    @drop_bears = false
    @dust_devils = false
    @season = SEASON_NONE
    @aurora = false
    @volcano = false
    @vines = false
    @thin_air = false
    @stampede = false
    @dust_storm = false
    @fireworks = false
    @stun = false
    @missile_aim = false
    @celestial = true
    @start_day = 0.0
  end

  def has_water?
    @water[0][1] > @water[0][0]
  end

  def spill?
    @crate_spill[0] + @crate_spill[1] + @crate_spill[2] > 0.0
  end
end

